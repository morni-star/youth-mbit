// YOUTH Car
youthCar.calibrateDrive(20)
youthCar.calibrateTurn(400, 50)
youthCar.headlight(YouthColor.Green)
youthCar.driveFor(YouthDir.Forward, 50, 1)
youthCar.turn(YouthSide.Right, 90)
youthCar.driveCm(YouthDir.Backward, 30)
youthCar.driveUntilCloser(40, 15)
youthCar.followToStation(40)
youthCar.driveShape(4, 30)
youthCar.turnSignal(YouthSide.Left, 3)
youthCar.emergencyLights(2)
youthCar.rainbow()
youthCar.underglowBrightness(30)
youthCar.carSound(YouthCarSound.Horn)
youthCar.servoSweep(YouthServo.S1, 0, 180, 1000)
youthCar.gate(YouthServo.S2, YouthGate.Open)
youthCar.onCloserThan(20, function () { youthCar.stop() })
youthCar.onLine(YouthLinePos.Lost, function () { youthCar.stop() })
youthCar.onObstacle(function () { youthMusic.beep(2) })
youthCar.onDark(function () { youthCar.headlight(YouthColor.White) })
// YOUTH Kit
youthKit.led(DigitalPin.P8, YouthOnOff.On)
youthKit.ledBrightness(AnalogPin.P0, 40)
youthKit.breathe(AnalogPin.P0, 2)
youthKit.setRgbType(YouthRgbType.CommonAnode)
youthKit.rgbColor(AnalogPin.P0, AnalogPin.P1, AnalogPin.P2, YouthColor.Cyan)
youthKit.onButton(DigitalPin.P12, function () { youthMusic.playJingle(YouthJingle.Doorbell, YouthPlayMode.Background) })
youthKit.onSound(DigitalPin.P13, function () { basic.showIcon(IconNames.Heart) })
youthKit.fan(AnalogPin.P1, 60)
youthKit.servo(AnalogPin.P2, 90)
youthKit.buzzerBeep(DigitalPin.P16, 2)
// YOUTH Music
youthMusic.setTempo(120)
youthMusic.playSong(YouthSong.FurElise, YouthPlayMode.Background)
youthMusic.playJingle(YouthJingle.PowerOn, YouthPlayMode.UntilDone)
youthMusic.playNotes("C4:4 D E F G:8", YouthPlayMode.UntilDone)
youthMusic.playEditorMelody("C D E F G A B C5 ", YouthPlayMode.UntilDone)
youthMusic.playEffect(YouthSfx.Rocket)
basic.forever(function () {
    youthCar.followLine(40)
    youthMusic.proximityBeep(youthCar.distance(), 5, 50)
    youthMusic.playValueOnScale(youthKit.ultrasonic(DigitalPin.P14, DigitalPin.P15), 0, 100, YouthScale.Pentatonic, 200)
    if (youthKit.joystickIs(AnalogPin.P1, AnalogPin.P2, DigitalPin.P8, YouthStick.Up)) youthCar.drive(YouthDir.Forward, 50)
    if (youthMusic.isPlaying()) youthMusic.stopMusic()
})
youthMusic.playPartySong(YouthPartySong.SilentNight, YouthPlayMode.UntilDone)
youthMusic.playKidsSong(YouthKidsSong.BrotherJohn, YouthPlayMode.Loop)
youthMusic.playJingle(YouthJingle.CartoonChase, YouthPlayMode.UntilDone)
